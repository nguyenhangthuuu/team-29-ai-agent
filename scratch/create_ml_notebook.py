            "    df[\"target_fwd_alpha_5d\"] = fwd_ret_asset - fwd_ret_bmk\n",
            "    df[\"target_binary_outperform\"] = (df[\"target_fwd_alpha_5d\"] > 0.0).astype(int)\n",
            "\n",
            "    return df"
